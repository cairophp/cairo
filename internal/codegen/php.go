// Package codegen generates PHP classes from .proto files: one class per
// message, one class of constants per enum, and per service an interface to
// implement and a typed client.
//
// Cairo already hands PHP each gRPC message as a protojson array, so the
// generated classes are plain PHP with typed properties plus fromArray() and
// toArray(); they need no protoc and no google/protobuf runtime.
package codegen

import (
	"bytes"
	"context"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/bufbuild/protocompile"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

// File is one generated PHP file, relative to the output directory.
type File struct {
	Path    string
	Content string
}

// Options for Generate.
type Options struct {
	// ImportPaths to resolve the .proto files and their imports; the
	// directory of each file is always included.
	ImportPaths []string
}

// Generate compiles the .proto files and returns the PHP files for them. It
// also returns autoload.php, a PSR-4 autoloader for the output directory.
func Generate(protos []string, opts Options) ([]File, error) {
	var out []File
	seen := map[string]bool{}
	for _, p := range protos {
		abs, err := filepath.Abs(p)
		if err != nil {
			return nil, err
		}
		paths := append([]string{filepath.Dir(abs)}, opts.ImportPaths...)
		c := protocompile.Compiler{Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{ImportPaths: paths})}
		files, err := c.Compile(context.Background(), filepath.Base(abs))
		if err != nil {
			return nil, fmt.Errorf("compile %s: %w", p, err)
		}
		for _, fd := range files {
			for _, f := range generateFile(fd) {
				if !seen[f.Path] {
					seen[f.Path] = true
					out = append(out, f)
				}
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	out = append(out, File{Path: "autoload.php", Content: autoload})
	return out, nil
}

// Write writes files under dir, creating directories as needed.
func Write(dir string, files []File) error {
	for _, f := range files {
		p := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(f.Content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

const autoload = `<?php
// Generated by cairo gen. Loads the generated classes (PSR-4, this directory).
spl_autoload_register(static function (string $class): void {
    $file = __DIR__ . '/' . str_replace('\\', '/', $class) . '.php';
    if (is_file($file)) {
        require $file;
    }
});
`

func generateFile(fd protoreflect.FileDescriptor) []File {
	ns := phpNamespace(fd)
	var out []File
	var walkMsgs func(protoreflect.MessageDescriptors)
	var walkEnums func(protoreflect.EnumDescriptors)
	walkEnums = func(es protoreflect.EnumDescriptors) {
		for i := 0; i < es.Len(); i++ {
			out = append(out, enumFile(ns, es.Get(i)))
		}
	}
	walkMsgs = func(ms protoreflect.MessageDescriptors) {
		for i := 0; i < ms.Len(); i++ {
			m := ms.Get(i)
			if m.IsMapEntry() {
				continue
			}
			out = append(out, messageFile(ns, m))
			walkEnums(m.Enums())
			walkMsgs(m.Messages())
		}
	}
	walkEnums(fd.Enums())
	walkMsgs(fd.Messages())
	for i := 0; i < fd.Services().Len(); i++ {
		out = append(out, serviceFile(ns, fd.Services().Get(i)))
		out = append(out, clientFile(ns, fd.Services().Get(i)))
	}
	return out
}

// ---- naming ----

// phpNamespace is option php_namespace, or the package in StudlyCase
// (foo.bar_baz -> Foo\BarBaz).
func phpNamespace(fd protoreflect.FileDescriptor) string {
	if o, ok := fd.Options().(*descriptorpb.FileOptions); ok && o.GetPhpNamespace() != "" {
		return o.GetPhpNamespace()
	}
	var parts []string
	for _, p := range strings.Split(string(fd.Package()), ".") {
		if p != "" {
			parts = append(parts, safeName(studly(p)))
		}
	}
	return strings.Join(parts, `\`)
}

func studly(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		up = false
		b.WriteRune(r)
	}
	return b.String()
}

