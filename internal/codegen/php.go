// safeName prefixes PHP reserved words, as protoc's PHP generator does.
func safeName(s string) string {
	if reserved[strings.ToLower(s)] {
		return "PB" + s
	}
	return s
}

// className is the PHP class for a message or enum: nested types are joined
// with an underscore (Outer_Inner).
func className(d protoreflect.Descriptor) string {
	var parts []string
	for cur := d; cur != nil; cur = cur.Parent() {
		if _, isFile := cur.(protoreflect.FileDescriptor); isFile {
			break
		}
		parts = append([]string{string(cur.Name())}, parts...)
	}
	return safeName(strings.Join(parts, "_"))
}

func fqcn(d protoreflect.Descriptor) string {
	ns := phpNamespace(d.ParentFile())
	if ns == "" {
		return `\` + className(d)
	}
	return `\` + ns + `\` + className(d)
}

// ---- messages ----

// wellKnown messages keep protojson's own shape (a string for Timestamp and
// Duration, any JSON for Struct and Value), so they stay plain PHP values.
func wellKnown(m protoreflect.MessageDescriptor) bool {
	return strings.HasPrefix(string(m.FullName()), "google.protobuf.")
}

type field struct {
	fd       protoreflect.FieldDescriptor
	prop     string // PHP property: the protojson (lowerCamelCase) name
	phpType  string // declared type
	def      string // default value
	nullable bool
}

func fieldsOf(m protoreflect.MessageDescriptor) []field {
	var out []field
	fs := m.Fields()
	for i := 0; i < fs.Len(); i++ {
		fd := fs.Get(i)
		f := field{fd: fd, prop: fd.JSONName()}
		switch {
		case fd.IsMap(), fd.IsList():
			f.phpType, f.def = "array", "[]"
		case fd.Kind() == protoreflect.MessageKind || fd.Kind() == protoreflect.GroupKind:
			if wellKnown(fd.Message()) {
				f.phpType, f.def, f.nullable = "mixed", "null", true
			} else {
				f.phpType, f.def, f.nullable = "?"+fqcn(fd.Message()), "null", true
			}
		default:
			t, d := scalar(fd.Kind())
			f.phpType, f.def = t, d
			if fd.HasPresence() {
				// proto3 optional and oneof members: null means "not set".
				f.phpType, f.def, f.nullable = "?"+t, "null", true
			}
		}
		out = append(out, f)
	}
	return out
}

func scalar(k protoreflect.Kind) (string, string) {
	switch k {
	case protoreflect.BoolKind:
		return "bool", "false"
	case protoreflect.StringKind, protoreflect.BytesKind:
		return "string", "''"
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		return "float", "0.0"
	default: // ints and enums
		return "int", "0"
	}
}

// fromValue is the PHP expression that turns protojson value $v into the
// property's PHP value, for a single (non-repeated) value of fd.
func fromValue(fd protoreflect.FieldDescriptor, v string) string {
	switch fd.Kind() {
	case protoreflect.MessageKind, protoreflect.GroupKind:
		if wellKnown(fd.Message()) {
			return v
		}
		return fqcn(fd.Message()) + "::fromArray((array) " + v + ")"
	case protoreflect.EnumKind:
		return fqcn(fd.Enum()) + "::value(" + v + ")"
	case protoreflect.BytesKind:
		return "(string) base64_decode((string) " + v + ")"
	case protoreflect.BoolKind:
		return "(bool) " + v
	case protoreflect.StringKind:
		return "(string) " + v
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		return "(float) " + v
	default:
		return "(int) " + v
	}
}

// toValue is the PHP expression that turns property value $v into protojson.
func toValue(fd protoreflect.FieldDescriptor, v string) string {
	switch fd.Kind() {
	case protoreflect.MessageKind, protoreflect.GroupKind:
		if wellKnown(fd.Message()) {
			return v
		}
		return v + "->toArray()"
	case protoreflect.BytesKind:
		return "base64_encode(" + v + ")"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
		protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "(string) " + v // protojson writes 64-bit integers as strings
	default:
		return v
	}
}

func messageFile(ns string, m protoreflect.MessageDescriptor) File {
	cls := className(m)
	fields := fieldsOf(m)
	var b bytes.Buffer
	header(&b, ns, m.ParentFile().Path())
	fmt.Fprintf(&b, "/** %s */\nfinal class %s\n{\n", m.FullName(), cls)
	for _, f := range fields {
		doc := phpDoc(f.fd)
		if doc != "" {
			fmt.Fprintf(&b, "    /** %s */\n", doc)
		}
		fmt.Fprintf(&b, "    public %s $%s = %s;\n", f.phpType, f.prop, f.def)
	}
	if len(fields) > 0 {
		b.WriteString("\n")
	}

	// constructor with named arguments: new HelloRequest(name: 'x')
	if len(fields) > 0 {
		b.WriteString("    public function __construct(\n")
		for _, f := range fields {
			fmt.Fprintf(&b, "        %s $%s = %s,\n", f.phpType, f.prop, f.def)
		}
		b.WriteString("    ) {\n")
		for _, f := range fields {
			fmt.Fprintf(&b, "        $this->%s = $%s;\n", f.prop, f.prop)
		}
		b.WriteString("    }\n\n")
	}

	// fromArray: protojson array -> object
	b.WriteString("    /** Builds the message from its protojson array (what Cairo passes to handlers). */\n")
	b.WriteString("    public static function fromArray(array $data): self\n    {\n        $m = new self();\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "        if (array_key_exists('%s', $data) && $data['%s'] !== null) {\n", f.prop, f.prop)
		switch {
		case f.fd.IsMap():
			fmt.Fprintf(&b, "            foreach ((array) $data['%s'] as $k => $v) {\n                $m->%s[%s] = %s;\n            }\n",
				f.prop, f.prop, mapKey(f.fd.MapKey(), "$k"), fromValue(f.fd.MapValue(), "$v"))
		case f.fd.IsList():
			fmt.Fprintf(&b, "            foreach ((array) $data['%s'] as $v) {\n                $m->%s[] = %s;\n            }\n",
				f.prop, f.prop, fromValue(f.fd, "$v"))
		default:
			fmt.Fprintf(&b, "            $m->%s = %s;\n", f.prop, fromValue(f.fd, "$data['"+f.prop+"']"))
		}
		b.WriteString("        }\n")
	}
	b.WriteString("        return $m;\n    }\n\n")

	// toArray: object -> protojson array
	b.WriteString("    /** The protojson array for this message (what Cairo sends back to Go). */\n")
	b.WriteString("    public function toArray(): array\n    {\n        $out = [];\n")
	for _, f := range fields {
		p := "$this->" + f.prop
		switch {
		case f.fd.IsMap():
			fmt.Fprintf(&b, "        $out['%s'] = (object) array_map(static fn ($v) => %s, %s);\n", f.prop, toValue(f.fd.MapValue(), "$v"), p)
		case f.fd.IsList():
			fmt.Fprintf(&b, "        $out['%s'] = array_values(array_map(static fn ($v) => %s, %s));\n", f.prop, toValue(f.fd, "$v"), p)
		case f.nullable:
			fmt.Fprintf(&b, "        if (%s !== null) {\n            $out['%s'] = %s;\n        }\n", p, f.prop, toValue(f.fd, p))
		default:
			fmt.Fprintf(&b, "        $out['%s'] = %s;\n", f.prop, toValue(f.fd, p))
		}
	}
	b.WriteString("        return $out;\n    }\n}\n")
	return File{Path: filePath(ns, cls), Content: b.String()}
}

// mapKey converts a protojson map key (always a string) to the PHP key.
func mapKey(fd protoreflect.FieldDescriptor, k string) string {
	switch fd.Kind() {
	case protoreflect.StringKind:
		return "(string) " + k
	case protoreflect.BoolKind:
		return "(" + k + " === 'true' || " + k + " === true) ? 'true' : 'false'"
	default:
		return "(int) " + k
	}
}

func phpDoc(fd protoreflect.FieldDescriptor) string {
	switch {
	case fd.IsMap():
		return fmt.Sprintf("@var array<%s, %s>", docType(fd.MapKey()), docType(fd.MapValue()))
	case fd.IsList():
		return fmt.Sprintf("@var list<%s>", docType(fd))
	case fd.Kind() == protoreflect.EnumKind:
		return "@see " + fqcn(fd.Enum())
	}
	return ""
}

func docType(fd protoreflect.FieldDescriptor) string {
	if fd.Kind() == protoreflect.MessageKind || fd.Kind() == protoreflect.GroupKind {
		if wellKnown(fd.Message()) {
			return "mixed"
		}
		return fqcn(fd.Message())
	}
	t, _ := scalar(fd.Kind())
	return t
}

// ---- enums ----

func enumFile(ns string, e protoreflect.EnumDescriptor) File {
	cls := className(e)
	var b bytes.Buffer
	header(&b, ns, e.ParentFile().Path())
	fmt.Fprintf(&b, "/** %s */\nfinal class %s\n{\n", e.FullName(), cls)
	vs := e.Values()
	for i := 0; i < vs.Len(); i++ {
		fmt.Fprintf(&b, "    public const %s = %d;\n", safeName(string(vs.Get(i).Name())), vs.Get(i).Number())
	}
	b.WriteString("\n    private const NAMES = [\n")
	for i := 0; i < vs.Len(); i++ {
		fmt.Fprintf(&b, "        %d => '%s',\n", vs.Get(i).Number(), vs.Get(i).Name())
	}
	b.WriteString("    ];\n\n")
	b.WriteString(`    /** The number for a protojson enum value (its name, or a number). */
    public static function value(int|string $v): int
    {
        if (is_int($v)) {
            return $v;
        }
        $n = array_search($v, self::NAMES, true);
        if ($n === false) {
            throw new \UnexpectedValueException("unknown ` + string(e.FullName()) + ` value $v");
        }
        return $n;
    }

    public static function name(int $v): string
    {
        return self::NAMES[$v] ?? (string) $v;
    }
}
`)
	return File{Path: filePath(ns, cls), Content: b.String()}
}

// ---- services ----

func serviceFile(ns string, s protoreflect.ServiceDescriptor) File {
	cls := safeName(string(s.Name())) + "Interface"
	var b bytes.Buffer
	header(&b, ns, s.ParentFile().Path())
	fmt.Fprintf(&b, "/**\n * %s. Implement it and register the class:\n *\n *     $grpc->service('%s', MyService::class);\n */\ninterface %s\n{\n",
		s.FullName(), s.FullName(), cls)
	ms := s.Methods()
	for i := 0; i < ms.Len(); i++ {
		m := ms.Get(i)
		if m.IsStreamingClient() || m.IsStreamingServer() {
			fmt.Fprintf(&b, "    // %s is a streaming method; streaming handlers come in a later milestone.\n", m.Name())
			continue
		}
		fmt.Fprintf(&b, "    public function %s(%s $request, \\Cairo\\Context $ctx): %s;\n",
			m.Name(), msgType(m.Input()), msgType(m.Output()))
	}
	b.WriteString("}\n")
	return File{Path: filePath(ns, cls), Content: b.String()}
}

// clientFile is a typed client for a service: one method per RPC, over
// Cairo\Grpc\Client. It carries the descriptors of the .proto file and its
// imports, so no .proto file is needed at run time.
func clientFile(ns string, s protoreflect.ServiceDescriptor) File {
	cls := safeName(string(s.Name())) + "Client"
	var b bytes.Buffer
	header(&b, ns, s.ParentFile().Path())
	fmt.Fprintf(&b, "/**\n * A client for %s. In a request handler or async() task only the\n * fiber waits for the reply.\n *\n *     $client = new %s('localhost:9000');\n *\n * Options are those of Cairo\\Grpc\\Client (tls, metadata, timeout).\n */\nfinal class %s\n{\n",
		s.FullName(), cls, cls)
	b.WriteString("    /** The .proto file and its imports, as a base64 FileDescriptorSet. */\n    public const DESCRIPTORS = ")
	enc := descriptorSet(s.ParentFile())
	for i := 0; i < len(enc); i += 96 {
		end := min(i+96, len(enc))
		if i > 0 {
			b.WriteString("\n        . ")
		}
		fmt.Fprintf(&b, "'%s'", enc[i:end])
	}
	b.WriteString(";\n\n    private \\Cairo\\Grpc\\Client $client;\n\n")
	b.WriteString("    /** @param array<string, mixed> $options */\n")
	b.WriteString("    public function __construct(string $target, array $options = [])\n    {\n")
	b.WriteString("        $this->client = new \\Cairo\\Grpc\\Client($target, $options + ['descriptors' => self::DESCRIPTORS]);\n    }\n")
	ms := s.Methods()
	for i := 0; i < ms.Len(); i++ {
		m := ms.Get(i)
		if m.IsStreamingClient() || m.IsStreamingServer() {
			fmt.Fprintf(&b, "\n    // %s is a streaming method; streaming calls come in a later milestone.\n", m.Name())
			continue
		}
		in, out := msgType(m.Input()), msgType(m.Output())
		arg := "$request->toArray()"
		if in == "array" {
			arg = "$request"
		}
		ret := out + "::fromArray($this->client->call('/%s/%s', %s, $options))"
		if out == "array" {
			ret = "$this->client->call('/%s/%s', %s, $options)"
		}
		fmt.Fprintf(&b, "\n    /**\n     * @param array{metadata?: array<string, string|list<string>>, timeout?: float} $options\n     * @throws \\Cairo\\Grpc\\Exception with the call's status code\n     */\n")
		fmt.Fprintf(&b, "    public function %s(%s $request, array $options = []): %s\n    {\n        return "+ret+";\n    }\n",
			m.Name(), in, out, s.FullName(), m.Name(), arg)
	}
	b.WriteString("}\n")
	return File{Path: filePath(ns, cls), Content: b.String()}
}

// descriptorSet is fd and everything it imports, as a base64
// FileDescriptorSet, dependencies first.
func descriptorSet(fd protoreflect.FileDescriptor) string {
	set := &descriptorpb.FileDescriptorSet{}
	seen := map[string]bool{}
	var add func(protoreflect.FileDescriptor)
	add = func(f protoreflect.FileDescriptor) {
		if seen[f.Path()] {
			return
		}
		seen[f.Path()] = true
		imports := f.Imports()
		for i := 0; i < imports.Len(); i++ {
			add(imports.Get(i).FileDescriptor)
		}
		fp := protodesc.ToFileDescriptorProto(f)
		fp.SourceCodeInfo = nil
		set.File = append(set.File, fp)
	}
	add(fd)
	raw, err := proto.MarshalOptions{Deterministic: true}.Marshal(set)
	if err != nil {
		panic(err)
	}
	return base64.StdEncoding.EncodeToString(raw)
}

func msgType(m protoreflect.MessageDescriptor) string {
	if wellKnown(m) {
		return "array"
	}
	return fqcn(m)
}

// ---- helpers ----

func header(b *bytes.Buffer, ns, source string) {
	fmt.Fprintf(b, "<?php\n// Generated by cairo gen from %s. Do not edit.\n\ndeclare(strict_types=1);\n\n", source)
	if ns != "" {
		fmt.Fprintf(b, "namespace %s;\n\n", ns)
	}
}

func filePath(ns, cls string) string {
	if ns == "" {
		return cls + ".php"
	}
	return strings.ReplaceAll(ns, `\`, "/") + "/" + cls + ".php"
}
